import Foundation

/// Ограничения `/files/uploadImage` на стороне сервера. Единственный владелец этих чисел:
/// `ImageFileStore` приводит к ним выбранное изображение, `FilesService` проверяет размер перед отправкой.
enum ImageUploadLimits {
    /// Максимальный размер файла — 10 МБ; при превышении сервер отвечает кодом 3002.
    static let maxFileSize = 10 * 1024 * 1024
    /// Максимальное число пикселей (ширина × высота) — 25 мегапикселей; при превышении сервер отвечает кодом 3002.
    /// Проверяется при подготовке файла (`ImageFileStore`): чтобы узнать размер кадра, нужно прочитать метаданные,
    /// а сетевой слой с содержимым файла не работает.
    static let maxPixels = 25_000_000
}
