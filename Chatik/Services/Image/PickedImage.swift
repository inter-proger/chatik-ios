import UIKit

/// Изображение, выбранное пользователем для загрузки на сервер.
enum PickedImage: Sendable {
    /// Уже декодированное изображение — например, снимок с камеры.
    case image(UIImage)
    /// Сырое содержимое файла (JPEG, HEIC, PNG…) — например, из галереи.
    /// Передаётся без декодирования, чтобы `ImageEncoder` сразу декодировал его в уменьшенном размере.
    case file(Data)
}
