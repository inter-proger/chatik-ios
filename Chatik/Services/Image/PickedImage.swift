import UIKit

/// Изображение, выбранное пользователем для загрузки на сервер.
enum PickedImage: Sendable {
    /// Уже декодированное изображение без файла — снимок с камеры.
    case image(UIImage)
    /// Оригинальный файл изображения (JPEG, PNG, WebP), скопированный во временную директорию — из галереи.
    /// Загружается на сервер как есть, без перекодирования и уменьшения.
    case file(ImageFile)
}
