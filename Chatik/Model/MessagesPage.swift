import Foundation

/// Страница сообщений переписки — ответ `/messages/getList`. Состоит из целых блоков.
///
/// Число сообщений ничего не говорит о конце переписки: страница набирается по местам в блоках, а место удалённого
/// сообщения остаётся занятым, поэтому сообщений может быть больше или меньше 40 — вплоть до 0 при `hasNext: true`.
/// Подгружать дальше нужно, пока `hasNext` равен `true`.
struct MessagesPage: Decodable, Equatable, Sendable {
    /// Сообщения по убыванию `messageId` — сначала самые новые.
    let messages: [Message]
    /// Первый блок, не попавший в страницу; передаётся в `blockId` за более старыми сообщениями.
    /// `nil`, если более старых сообщений нет.
    let nextBlockId: Int?
    /// Без `receivedAfter` — есть ли блоки старше этой страницы. С `receivedAfter` — новых сообщений больше,
    /// чем помещается на страницу: кэш нужно сбросить, а страница совпадает с первой страницей без фильтра.
    let hasNext: Bool
    /// Только при `receivedAfter` и `hasNext: false`: блоки, где после отметки изменились или удалились старые
    /// сообщения, по убыванию id, не больше 10. Ровно 10 — их может быть больше, кэш нужно сбросить.
    var updatedBlockIds: [Int]? = nil
}
