import Foundation

/// Состояние синхронизации списка переписок; хранится в БД вместе с кэшем списка.
///
/// Водяные знаки хранятся, а не вычисляются из максимума по кэшу: подъём переписки по ответу `/messages/send`
/// и прерванная сверка информации иначе приводили бы к потере изменений.
struct ConversationListState: Equatable {
    /// Получена ли с сервера хотя бы первая страница списка.
    var isLoaded = false
    /// Есть ли на сервере переписки после загруженных.
    var hasMorePages = false
    /// Все переписки, поднявшиеся до этой метки, известны клиенту; дельта позиций запрашивается от неё.
    /// `nil` — дельту запросить не от чего, нужна полная загрузка.
    var positionWatermark: ServerTime?
    /// Потолок для `positionWatermark` после неудачного `getBatch`: пропущенную переписку вернёт только дельта
    /// позиций, поэтому водяной знак не должен подняться выше её позиции. Снимается успешной синхронизацией.
    var positionWatermarkCeiling: ServerTime?
    /// Все изменения информации до этой метки известны; сверка информации запрашивается от неё.
    var infoWatermark: ServerTime?
}
