import Foundation

/// Загрузка данных пользователя при открытии сессии — всё, что о сервисах с такими данными (черновики, очередь
/// отправки) знает `SessionService`. Это данные, которых нет на сервере: они переживают выход из аккаунта,
/// а в память загружаются только данные пользователя открытой сессии.
@MainActor
protocol SessionDataLoading: AnyObject, Sendable {
    /// Загружает данные пользователя из БД в память; повторный вызов для того же пользователя после успешной
    /// загрузки ничего не делает.
    /// - Parameter userId: пользователь открытой сессии.
    func load(userId: Int) async
}
